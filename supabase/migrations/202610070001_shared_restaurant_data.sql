create or replace function public.sincronizar_status_mesa()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  alvo uuid;
  quantidade_itens integer;
begin
  alvo := case when tg_op = 'DELETE' then old.mesa_id else new.mesa_id end;
  select count(*) into quantidade_itens from public.itens_pedido where mesa_id = alvo;
  if quantidade_itens = 0 then
    update public.mesas set status = 'livre' where id = alvo;
  elsif tg_op = 'INSERT' then
    update public.mesas set status = 'ocupada' where id = alvo;
  else
    update public.mesas set status = case when status = 'conta' then 'conta' else 'ocupada' end where id = alvo;
  end if;
  if tg_op = 'UPDATE' and old.mesa_id <> new.mesa_id then
    update public.mesas set status = case when exists (select 1 from public.itens_pedido where mesa_id = old.mesa_id) then 'ocupada' else 'livre' end where id = old.mesa_id;
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

drop trigger if exists itens_pedido_sincronizar_mesa on public.itens_pedido;
create trigger itens_pedido_sincronizar_mesa
  after insert or update or delete on public.itens_pedido
  for each row execute procedure public.sincronizar_status_mesa();

create or replace function public.pedir_conta(p_mesa_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Sessão necessária.'; end if;
  update public.mesas set status = 'conta' where id = p_mesa_id and ativa;
  if not found then raise exception 'Mesa não encontrada ou inativa.'; end if;
end;
$$;

create or replace function public.fechar_conta(p_mesa_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  mesa public.mesas%rowtype;
  linhas jsonb;
  subtotal_calculado numeric(10,2);
  taxa_percentual numeric(6,2);
  taxa_valor numeric(10,2);
  total_calculado numeric(10,2);
  venda public.vendas%rowtype;
begin
  if not public.usuario_caixa() then raise exception 'Somente o caixa pode fechar a conta.'; end if;
  select * into mesa from public.mesas where id = p_mesa_id and ativa for update;
  if not found then raise exception 'Mesa não encontrada ou inativa.'; end if;
  select
    coalesce(jsonb_agg(jsonb_build_object(
      'id', i.id, 'itemId', i.produto_id, 'name', i.produto,
      'qty', i.quantidade, 'price', i.valor_unitario, 'note', i.observacao,
      'at', (extract(epoch from i.criado_em) * 1000)::bigint,
      'waiter', i.garcom, 'waiterId', i.garcom_id
    ) order by i.criado_em), '[]'::jsonb),
    coalesce(sum(i.quantidade * i.valor_unitario), 0)
  into linhas, subtotal_calculado
  from public.itens_pedido i where i.mesa_id = p_mesa_id;
  if jsonb_array_length(linhas) = 0 then raise exception 'Não há itens para fechar nesta mesa.'; end if;
  select case when taxa_servico_ativa then taxa_servico_percentual else 0 end
  into taxa_percentual from public.configuracoes_restaurante where id = true;
  taxa_percentual := coalesce(taxa_percentual, 0);
  taxa_valor := round(subtotal_calculado * taxa_percentual / 100, 2);
  total_calculado := subtotal_calculado + taxa_valor;
  insert into public.vendas (mesa_id, mesa_numero, snapshot, subtotal, taxa_percentual, taxa_valor, total, fechado_por)
  values (mesa.id, mesa.numero, linhas, subtotal_calculado, taxa_percentual, taxa_valor, total_calculado, auth.uid())
  returning * into venda;
  delete from public.itens_pedido where mesa_id = p_mesa_id;
  update public.mesas set status = 'livre' where id = p_mesa_id;
  return jsonb_build_object(
    'id', venda.id, 'at', (extract(epoch from venda.fechado_em) * 1000)::bigint,
    'table', venda.mesa_numero, 'saleNumber', venda.numero_venda, 'lines', venda.snapshot,
    'subtotal', venda.subtotal, 'serviceChargePercent', venda.taxa_percentual,
    'serviceCharge', venda.taxa_valor, 'total', venda.total
  );
end;
$$;

