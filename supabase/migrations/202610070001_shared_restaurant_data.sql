create extension if not exists pgcrypto;

create table if not exists public.garcons (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  usuario text not null unique,
  funcao text not null default 'garcom' check (funcao in ('caixa', 'garcom')),
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

create or replace function public.usuario_caixa()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.garcons g
    where g.id = auth.uid() and g.funcao = 'caixa' and g.ativo
  );
$$;

create or replace function public.criar_perfil_garcom()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.garcons (id, nome, usuario, funcao)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'usuario', new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'funcao', 'garcom')
  )
  on conflict (id) do update set
    nome = excluded.nome,
    usuario = excluded.usuario;
  return new;
end;
$$;

drop trigger if exists criar_perfil_apos_signup on auth.users;
create trigger criar_perfil_apos_signup
  after insert on auth.users
  for each row execute procedure public.criar_perfil_garcom();

