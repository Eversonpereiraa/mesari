create or replace function public.enviar_pedido(p_mesa_id uuid, p_itens jsonb, p_imprimir boolean default true)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_mesa      public.mesas;
  v_it        jsonb;
  v_prod      record;
  v_qtd       int;
  v_obs       text;
  v_garcom_id uuid := auth.uid();
  v_garcom    text;
  v_rid       integer;
  v_adicional boolean;
  v_total     int := 0;
  v_setor     text;
  v_por_setor jsonb := '{}'::jsonb;
begin
  if v_garcom_id is null then raise exception 'Faça login para continuar'; end if;
  select nome, restaurante_id into v_garcom, v_rid from public.profiles where id = v_garcom_id and ativo;
  if v_garcom is null then raise exception 'Usuário sem perfil ativo'; end if;
  perform public.exigir_assinatura();

  if p_itens is null or jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'Escolha pelo menos um item';
  end if;

  select * into v_mesa from public.mesas where id = p_mesa_id and ativa and restaurante_id = v_rid for update;
  if not found then raise exception 'Mesa não encontrada ou inativa'; end if;

  v_adicional := exists (select 1 from public.itens_pedido where mesa_id = p_mesa_id);

  for v_it in select * from jsonb_array_elements(p_itens) loop
    v_qtd := (v_it->>'quantidade')::int;
    if v_qtd is null or v_qtd < 1 or v_qtd > 99 then raise exception 'Quantidade inválida (use de 1 a 99)'; end if;
    v_obs := nullif(trim(coalesce(v_it->>'observacao', '')), '');

    select p.id, p.nome, p.preco, coalesce(c.setor, 'cozinha') as setor into v_prod
      from public.produtos p left join public.categorias c on c.id = p.categoria_id
     where p.id = (v_it->>'produto_id')::uuid and p.ativo and p.restaurante_id = v_rid;
    if not found then raise exception 'Produto não encontrado ou inativo'; end if;

    insert into public.itens_pedido
      (restaurante_id, mesa_id, produto_id, produto_nome, quantidade, valor_unitario, observacao, garcom_id, garcom_nome)
    values (v_rid, p_mesa_id, v_prod.id, v_prod.nome, v_qtd, v_prod.preco, v_obs, v_garcom_id, v_garcom);

    v_total := v_total + 1;
    v_setor := v_prod.setor;
    if v_setor <> 'nenhum' then
      v_por_setor := jsonb_set(v_por_setor, array[v_setor],
        coalesce(v_por_setor->v_setor, '[]'::jsonb) || jsonb_build_array(jsonb_strip_nulls(jsonb_build_object(
          'produto', v_prod.nome, 'quantidade', v_qtd, 'valor_unitario', v_prod.preco, 'observacao', v_obs))),
        true);
    end if;
  end loop;

  if p_imprimir then
    for v_setor in select jsonb_object_keys(v_por_setor) loop
      insert into public.pedidos_cozinha (restaurante_id, mesa_numero, setor, garcom_nome, adicional, itens)
      values (v_rid, v_mesa.numero, v_setor, v_garcom, v_adicional, v_por_setor->v_setor);
    end loop;
  end if;

  return v_total;
end;
$$;

create or replace function public.fechar_conta(p_mesa_id uuid, p_pagamentos jsonb)
returns public.vendas
language plpgsql
security definer
set search_path = public
as $$
declare
  v_mesa   public.mesas;
  v_cfg    public.restaurante;
  v_itens  jsonb;
  v_sub    numeric(10,2);
  v_taxa   numeric(10,2) := 0;
  v_total  numeric(10,2);
  v_nome   text;
  v_garcom text;
  v_venda  public.vendas;
  v_pag    jsonb;
begin
  if not public.is_caixa() then raise exception 'Apenas o caixa pode fechar contas'; end if;

  select * into v_mesa from public.mesas where id = p_mesa_id and restaurante_id = public.meu_restaurante() for update;
  if not found then raise exception 'Mesa não encontrada'; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'produto', produto_nome, 'quantidade', quantidade, 'valor_unitario', valor_unitario,
           'observacao', observacao, 'garcom', garcom_nome) order by criado_em), '[]'::jsonb),
         coalesce(sum(quantidade * valor_unitario), 0)
    into v_itens, v_sub
    from public.itens_pedido where mesa_id = p_mesa_id;

  if jsonb_array_length(v_itens) = 0 then raise exception 'A mesa não tem itens para fechar'; end if;

  select * into v_cfg from public.restaurante where id = v_mesa.restaurante_id;
  if v_cfg.taxa_servico_ativa then v_taxa := round(v_sub * v_cfg.taxa_servico_percentual / 100, 2); end if;
  v_total := v_sub + v_taxa;

  v_pag := public._validar_pagamentos(p_pagamentos, v_total);

  select nome into v_nome from public.profiles where id = auth.uid();
  select garcom_nome into v_garcom from public.itens_pedido
   where mesa_id = p_mesa_id and garcom_nome is not null order by criado_em limit 1;

  insert into public.vendas
    (restaurante_id, mesa_numero, itens, subtotal, taxa_servico, total, pagamentos, garcom_nome, fechado_por, fechado_por_nome)
  values (v_mesa.restaurante_id, v_mesa.numero, v_itens, v_sub, v_taxa, v_total, v_pag, v_garcom, auth.uid(), v_nome)
  returning * into v_venda;

  delete from public.itens_pedido where mesa_id = p_mesa_id;
  update public.mesas set status = 'livre', solicitada_em = null where id = p_mesa_id;

  return v_venda;
end;
$$;

create or replace function public.atualizar_status_pedido_externo(p_id uuid, p_status text, p_entregador text default null, p_motivo text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_p public.pedidos_externos;
begin
  if not public.is_caixa() then raise exception 'Apenas o caixa pode alterar pedidos'; end if;
  if p_status = 'entregue' then raise exception 'Para concluir o pedido, use o pagamento (concluir_pedido_externo)'; end if;
  if p_status not in ('novo', 'preparo', 'pronto', 'saiu', 'cancelado') then raise exception 'Status inválido: %', p_status; end if;

  select * into v_p from public.pedidos_externos where id = p_id and restaurante_id = public.meu_restaurante() for update;
  if not found then raise exception 'Pedido não encontrado'; end if;
  if v_p.status in ('entregue', 'cancelado') then raise exception 'Este pedido já foi finalizado'; end if;
  if p_status = 'saiu' and v_p.tipo <> 'entrega' then raise exception 'Só pedidos de entrega saem para entrega'; end if;
  if p_status = 'cancelado' and nullif(trim(coalesce(p_motivo, '')), '') is null then
    raise exception 'Informe o motivo do cancelamento';
  end if;

  update public.pedidos_externos
     set status = p_status,
         entregador = case when p_status = 'saiu' then nullif(trim(coalesce(p_entregador, '')), '') else entregador end,
         motivo_cancelamento = case when p_status = 'cancelado' then trim(p_motivo) else motivo_cancelamento end,
         finalizado_em = case when p_status = 'cancelado' then now() else finalizado_em end
   where id = p_id;
end;
$$;

create or replace function public.concluir_pedido_externo(p_id uuid, p_pagamentos jsonb)
returns public.vendas
