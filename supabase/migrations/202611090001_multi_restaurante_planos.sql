update auth.users u
   set email = p.usuario || '@r100100.mesari.local', updated_at = now(),
       raw_app_meta_data = coalesce(u.raw_app_meta_data, '{}'::jsonb) || jsonb_build_object('restaurante_id', 1)
  from public.profiles p
 where p.id = u.id and p.restaurante_id = 1 and u.email like '%@mesari.local';

update auth.identities i
   set identity_data = i.identity_data || jsonb_build_object('email', u.email), updated_at = now()
  from auth.users u
 where u.id = i.user_id and i.provider = 'email' and u.email like '%@r100100.mesari.local';

