create or replace function public.reservar_impressao(p_estacao text, p_tipos text[] default null, p_limite integer default 3)
returns setof jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rid integer := public.meu_restaurante();
begin
  if not public.is_caixa() then raise exception 'Somente o caixa imprime a fila de impressão'; end if;

  update public.fila_impressao
     set status = 'falhou', erro = coalesce(erro, 'A estação parou de responder durante a impressão.'), reservado_em = null
   where restaurante_id = v_rid and status = 'imprimindo'
     and reservado_em < now() - interval '2 minutes' and tentativas >= 5;

  return query
  with alvo as (
    select f.id from public.fila_impressao f
     where f.restaurante_id = v_rid
       and ((f.status = 'pendente' and f.proxima_tentativa_em <= now())
            or (f.status = 'imprimindo' and f.reservado_em < now() - interval '2 minutes'))
       and f.tentativas < 5
       and f.liberado_em > now() - interval '3 hours'
       and (p_tipos is null or f.tipo = any (p_tipos))
     order by f.criado_em
     limit greatest(1, least(coalesce(p_limite, 3), 20))
     for update skip locked
  ), reservados as (
    update public.fila_impressao f
       set status = 'imprimindo', reservado_em = now(), reservado_por = auth.uid(),
           estacao = left(coalesce(nullif(trim(p_estacao), ''), 'Estação'), 80),
           tentativas = f.tentativas + 1
      from alvo where f.id = alvo.id
    returning f.*
  )
  select to_jsonb(r) || jsonb_build_object(
           'comanda', (select to_jsonb(pc) from public.pedidos_cozinha pc where pc.id = r.pedido_cozinha_id))
    from reservados r
   order by r.criado_em;
end;
$$;

