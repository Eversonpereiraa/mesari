create or replace function public.criar_usuario(p_usuario text, p_senha text, p_nome text, p_papel text default 'garcom')
returns uuid
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_id     uuid := gen_random_uuid();
  v_user   text := lower(trim(p_usuario));
  v_rid    integer := public.meu_restaurante();
  v_codigo text;
  v_email  text;
begin
  if not public.is_caixa() then raise exception 'Apenas o caixa pode criar usuários'; end if;
  perform public.exigir_assinatura();
  if v_user !~ '^[a-z0-9._-]{3,30}$' then
    raise exception 'Usuário inválido: use de 3 a 30 letras minúsculas, números, ponto, traço ou _';
  end if;
  if length(coalesce(p_senha, '')) < 6 then raise exception 'A senha precisa ter pelo menos 6 caracteres'; end if;
  if coalesce(trim(p_nome), '') = '' then raise exception 'Informe o nome'; end if;
  if p_papel not in ('caixa', 'garcom') then raise exception 'Papel inválido'; end if;

  select codigo into v_codigo from public.restaurante where id = v_rid;
  v_email := v_user || '@r' || v_codigo || '.mesari.local';

  if exists (select 1 from public.profiles where restaurante_id = v_rid and usuario = v_user)
     or exists (select 1 from auth.users where email = v_email) then
    raise exception 'Esse usuário já existe';
  end if;

  insert into auth.users (
    instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change_token_new, email_change
  ) values (
    '00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', v_email,
    extensions.crypt(p_senha, extensions.gen_salt('bf')), now(),
    jsonb_build_object('provider', 'email', 'providers', jsonb_build_array('email'), 'restaurante_id', v_rid, 'papel', p_papel),
    jsonb_build_object('nome', trim(p_nome)),
    now(), now(), '', '', '', ''
  );

  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), v_id, v_id::text,
          jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true),
          'email', now(), now(), now());

  insert into public.profiles (id, restaurante_id, usuario, nome, papel)
  values (v_id, v_rid, v_user, trim(p_nome), p_papel)
  on conflict (id) do update set usuario = excluded.usuario, nome = excluded.nome, papel = excluded.papel;

  return v_id;
end;
$$;

