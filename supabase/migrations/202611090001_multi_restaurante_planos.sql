revoke all on public.profiles, public.restaurante, public.categorias, public.produtos, public.mesas, public.itens_pedido,
              public.vendas, public.resumo_diario, public.pedidos_cozinha, public.pedidos_externos,
              public.salao_areas, public.salao_elementos from anon;
revoke insert, update, delete, truncate on public.profiles, public.restaurante, public.vendas, public.resumo_diario,
              public.pedidos_cozinha, public.pedidos_externos from authenticated;
revoke truncate on public.categorias, public.produtos, public.mesas, public.itens_pedido,
              public.salao_areas, public.salao_elementos from authenticated;
grant update (nome, usuario, ativo, papel) on public.profiles to authenticated;
grant update (nome, endereco, telefone, cnpj, instagram, logo_url, taxa_servico_ativa, taxa_servico_percentual,
              logo_impressao_url, imprimir_logo, rodape_conta) on public.restaurante to authenticated;

-- ---------------------------------------------------------------------------------------------
-- 9. Storage do logo: cada restaurante na sua pasta ("<id>/arquivo")
-- ---------------------------------------------------------------------------------------------
drop policy if exists marca_caixa_select on storage.objects;
drop policy if exists marca_caixa_insert on storage.objects;
drop policy if exists marca_caixa_update on storage.objects;
drop policy if exists marca_caixa_delete on storage.objects;
create policy marca_caixa_select on storage.objects for select to authenticated
  using (bucket_id = 'marca' and public.is_caixa() and (storage.foldername(name))[1] = public.meu_restaurante()::text);
create policy marca_caixa_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'marca' and public.is_caixa() and (storage.foldername(name))[1] = public.meu_restaurante()::text);
create policy marca_caixa_update on storage.objects for update to authenticated
  using (bucket_id = 'marca' and public.is_caixa() and (storage.foldername(name))[1] = public.meu_restaurante()::text)
  with check (bucket_id = 'marca' and public.is_caixa() and (storage.foldername(name))[1] = public.meu_restaurante()::text);
create policy marca_caixa_delete on storage.objects for delete to authenticated
  using (bucket_id = 'marca' and public.is_caixa() and (storage.foldername(name))[1] = public.meu_restaurante()::text);

