create or replace function public._limite_mesas()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_p public.planos;
  v_n integer;
begin
  if new.ativa and (tg_op = 'INSERT' or not old.ativa) then
    v_p := public.plano_do_restaurante(new.restaurante_id);
    if v_p.max_mesas is not null then
      select count(*) into v_n from public.mesas where restaurante_id = new.restaurante_id and ativa;
      if v_n > v_p.max_mesas then
        raise exception 'O plano % permite até % mesas. Para ter mais, mude de plano em "Meu plano".', v_p.nome, v_p.max_mesas;
      end if;
    end if;
  end if;
  return null;
end;
$$;

drop trigger if exists mesas_limite_plano on public.mesas;
create trigger mesas_limite_plano
  after insert or update of ativa on public.mesas
  for each row execute procedure public._limite_mesas();

create or replace function public._limite_usuarios()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_p public.planos;
  v_n integer;
  v_max integer;
begin
  if new.ativo and (tg_op = 'INSERT' or not old.ativo or old.papel is distinct from new.papel) then
    v_p := public.plano_do_restaurante(new.restaurante_id);
    v_max := case new.papel when 'caixa' then v_p.max_caixas else v_p.max_garcons end;
    if v_max is not null then
      select count(*) into v_n from public.profiles
       where restaurante_id = new.restaurante_id and ativo and papel = new.papel;
      if v_n > v_max then
        raise exception 'O plano % permite até % %. Para ter mais, mude de plano em "Meu plano".',
          v_p.nome, v_max, case new.papel when 'caixa' then 'usuários de caixa' else 'garçons' end;
      end if;
    end if;
  end if;
  return null;
end;
$$;

drop trigger if exists profiles_limite_plano on public.profiles;
create trigger profiles_limite_plano
  after insert or update of ativo, papel on public.profiles
  for each row execute procedure public._limite_usuarios();

