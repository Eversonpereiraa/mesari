create or replace function public.criar_pedido_externo(p_dados jsonb, p_imprimir boolean default true)
returns public.pedidos_externos
language plpgsql
security definer
set search_path = public
as $$
declare
  v_canal  text := lower(coalesce(nullif(trim(p_dados->>'canal'), ''), 'whatsapp'));
  v_tipo   text := lower(coalesce(nullif(trim(p_dados->>'tipo'), ''), 'entrega'));
  v_nome   text := nullif(trim(coalesce(p_dados->>'cliente_nome', '')), '');
  v_tel    text := nullif(regexp_replace(coalesce(p_dados->>'telefone', ''), '\D', '', 'g'), '');
  v_end    text := nullif(trim(coalesce(p_dados->>'endereco', '')), '');
  v_bairro text := nullif(trim(coalesce(p_dados->>'bairro', '')), '');
  v_ref    text := nullif(trim(coalesce(p_dados->>'referencia', '')), '');
  v_obs    text := nullif(trim(coalesce(p_dados->>'observacao', '')), '');
  v_rid    integer := public.meu_restaurante();
  v_it     jsonb;
  v_prod   record;
  v_qtd    int;
  v_iobs   text;
  v_nomeit text;
  v_valor  numeric(10,2);
  v_itens  jsonb := '[]'::jsonb;
  v_sub    numeric(10,2) := 0;
  v_taxa   numeric(10,2) := 0;
  v_desc   numeric(10,2) := 0;
  v_total  numeric(10,2);
  v_pp     jsonb := null;
  v_forma  text;
  v_troco  numeric(10,2);
  v_pago   boolean;
  v_usuario text;
  v_dia    int;
  v_auto   boolean;
  v_pedido public.pedidos_externos;
begin
  if not public.is_caixa() then raise exception 'Apenas o caixa pode lançar pedidos de delivery'; end if;
  perform public.exigir_assinatura();
  if not (public.plano_do_restaurante(v_rid)).delivery then
    raise exception 'O delivery está disponível a partir do plano Profissional. Mude de plano em "Meu plano".';
  end if;
  if p_dados is null or jsonb_typeof(p_dados) <> 'object' then raise exception 'Dados do pedido inválidos'; end if;
  if v_canal not in ('whatsapp', 'telefone', 'papel', 'app', 'balcao', 'outro') then raise exception 'Canal inválido'; end if;
  if v_tipo not in ('entrega', 'retirada', 'balcao') then raise exception 'Tipo de pedido inválido'; end if;
  if v_tel is not null and length(v_tel) not between 10 and 13 then raise exception 'Telefone inválido: use DDD + número'; end if;
  if v_tipo = 'entrega' and v_end is null then raise exception 'Informe o endereço de entrega'; end if;
  if v_tipo = 'entrega' and v_nome is null then raise exception 'Informe o nome do cliente'; end if;
  if v_tipo = 'retirada' and v_nome is null then raise exception 'Informe o nome de quem vai retirar'; end if;

  if jsonb_typeof(p_dados->'itens') is distinct from 'array' or jsonb_array_length(p_dados->'itens') = 0 then
    raise exception 'Adicione pelo menos um item';
  end if;
  if jsonb_array_length(p_dados->'itens') > 60 then raise exception 'Muitos itens em um só pedido (máximo 60 linhas)'; end if;

  for v_it in select * from jsonb_array_elements(p_dados->'itens') loop
    v_qtd := (v_it->>'quantidade')::int;
    if v_qtd is null or v_qtd < 1 or v_qtd > 99 then raise exception 'Quantidade inválida (use de 1 a 99)'; end if;
    v_iobs := nullif(trim(coalesce(v_it->>'observacao', '')), '');

    if nullif(v_it->>'produto_id', '') is not null then
      select p.id, p.nome, p.preco into v_prod from public.produtos p
       where p.id = (v_it->>'produto_id')::uuid and p.ativo and p.restaurante_id = v_rid;
      if not found then raise exception 'Produto não encontrado ou inativo'; end if;
      v_nomeit := v_prod.nome;
      v_valor  := v_prod.preco;
      v_itens := v_itens || jsonb_build_array(jsonb_strip_nulls(jsonb_build_object(
        'produto_id', v_prod.id, 'produto', v_nomeit, 'quantidade', v_qtd,
        'valor_unitario', v_valor, 'observacao', v_iobs, 'avulso', false)));
    else
      v_nomeit := nullif(trim(coalesce(v_it->>'nome', '')), '');
      if v_nomeit is null then raise exception 'Informe o nome do item avulso'; end if;
      v_valor := round((v_it->>'valor_unitario')::numeric, 2);
      if v_valor is null or v_valor < 0 or v_valor > 9999 then raise exception 'Valor inválido para o item %', v_nomeit; end if;
      v_itens := v_itens || jsonb_build_array(jsonb_strip_nulls(jsonb_build_object(
        'produto', v_nomeit, 'quantidade', v_qtd, 'valor_unitario', v_valor, 'observacao', v_iobs, 'avulso', true)));
    end if;
    v_sub := v_sub + v_qtd * v_valor;
  end loop;

  if v_tipo = 'entrega' then
    select coalesce(taxa_entrega, 0) into v_taxa from public.restaurante where id = v_rid;
    v_taxa := coalesce(v_taxa, 0);
  end if;

  v_desc := round(coalesce(nullif(p_dados->>'desconto', '')::numeric, 0), 2);
  if v_desc < 0 or v_desc > v_sub then raise exception 'Desconto inválido'; end if;
  v_total := v_sub + v_taxa - v_desc;

  if jsonb_typeof(p_dados->'pagamento_previsto') = 'object' then
    v_forma := lower(nullif(trim(coalesce(p_dados->'pagamento_previsto'->>'forma', '')), ''));
    if v_forma is not null and v_forma not in ('dinheiro', 'pix', 'credito', 'debito') then
      raise exception 'Forma de pagamento inválida: %', v_forma;
    end if;
    v_pago := coalesce((p_dados->'pagamento_previsto'->>'pago')::boolean, false);
    v_troco := nullif(p_dados->'pagamento_previsto'->>'troco_para', '')::numeric;
    if v_troco is not null and (v_forma is distinct from 'dinheiro' or v_troco < v_total) then
      raise exception 'O valor do troco deve ser em dinheiro e maior ou igual ao total';
    end if;
    v_pp := jsonb_strip_nulls(jsonb_build_object('forma', v_forma, 'pago', v_pago, 'troco_para', v_troco));
  end if;

  select nome into v_usuario from public.profiles where id = auth.uid();

  v_auto := p_imprimir
    and coalesce((select delivery_imprimir_ao_criar from public.config_impressao where restaurante_id = v_rid), true);

  perform pg_advisory_xact_lock(hashtext('pedidos_externos_numero_dia:' || v_rid));
  select coalesce(max(numero_dia), 0) + 1 into v_dia
    from public.pedidos_externos
   where restaurante_id = v_rid
     and (criado_em at time zone 'America/Sao_Paulo')::date = (now() at time zone 'America/Sao_Paulo')::date;

  insert into public.pedidos_externos
    (restaurante_id, numero_dia, canal, tipo, cliente_nome, telefone, endereco, bairro, referencia,
     itens, subtotal, taxa_entrega, desconto, total, pagamento_previsto, observacao,
     criado_por, criado_por_nome, status)
  values
    (v_rid, v_dia, v_canal, v_tipo, v_nome, v_tel,
     case when v_tipo = 'entrega' then v_end end,
     case when v_tipo = 'entrega' then v_bairro end,
     case when v_tipo = 'entrega' then v_ref end,
     v_itens, v_sub, v_taxa, v_desc, v_total, v_pp, v_obs,
     auth.uid(), v_usuario, case when v_auto then 'preparo' else 'novo' end)
  returning * into v_pedido;

  if v_auto then perform public._comanda_pedido_externo(v_pedido); end if;
  return v_pedido;
end;
$$;

create or replace function public.agregar_vendas(p_de timestamptz, p_ate timestamptz)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with v as (
    select id, total, origem, pagamentos, itens
      from public.vendas
     where restaurante_id = public.meu_restaurante()
       and fechada_em >= greatest(p_de, public.historico_inicio()) and fechada_em < p_ate
  ),
  pag as (
    select v.id, coalesce(p ->> 'forma', 'nao_informado') as forma, coalesce((p ->> 'valor')::numeric, v.total) as valor
      from v cross join lateral jsonb_array_elements(
        case when jsonb_typeof(v.pagamentos) = 'array' and jsonb_array_length(v.pagamentos) > 0
             then v.pagamentos else '[null]'::jsonb end) p
  ),
  itens as (
    select coalesce(i ->> 'produto', i ->> 'produto_nome', i ->> 'name') as nome,
           coalesce((i ->> 'quantidade')::numeric, (i ->> 'qty')::numeric, 0) as qtd,
           coalesce((i ->> 'valor_unitario')::numeric, (i ->> 'price')::numeric, 0) as preco
      from v cross join lateral jsonb_array_elements(
        case when jsonb_typeof(v.itens) = 'array' then v.itens else '[]'::jsonb end) i
  )
  select jsonb_build_object(
    'total', coalesce((select sum(total) from v), 0),
    'contas', (select count(*) from v),
    'por_forma', coalesce((select jsonb_object_agg(forma, jsonb_build_object('total', t, 'contas', c))
                             from (select forma, sum(valor) t, count(distinct id) c from pag group by forma) x), '{}'::jsonb),
    'por_origem', coalesce((select jsonb_object_agg(origem, jsonb_build_object('total', t, 'quantidade', c))
                              from (select coalesce(origem, 'mesa') origem, sum(total) t, count(*) c from v group by 1) x), '{}'::jsonb),
    'top_itens', coalesce((select jsonb_agg(jsonb_build_object('nome', nome, 'quantidade', q, 'total', t) order by q desc, t desc)
                             from (select nome, sum(qtd) q, round(sum(qtd * preco), 2) t
                                     from itens where nome is not null group by nome order by 2 desc, 3 desc limit 20) x), '[]'::jsonb)
  );
$$;

create or replace function public.fechar_resumo_dia(p_dia date)
