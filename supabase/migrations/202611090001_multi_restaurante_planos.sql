-- Plano em vigor (sem assinatura: Essencial).
create or replace function public.plano_do_restaurante(p_restaurante integer)
returns public.planos
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select p from public.assinaturas a join public.planos p on p.id = a.plano_id where a.restaurante_id = p_restaurante),
    (select p from public.planos p where p.id = 'essencial')
  );
$$;

-- Assinatura válida: teste/ativa/cancelada até o fim do período; atrasada com 5 dias de tolerância.
create or replace function public.assinatura_ativa(p_restaurante integer)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select case
      when a.status in ('teste', 'ativa', 'cancelada') then a.periodo_fim > now()
      when a.status = 'atrasada' then a.periodo_fim + interval '5 days' > now()
      else false
    end
    from public.assinaturas a where a.restaurante_id = p_restaurante
  ), false);
$$;

create or replace function public.exigir_assinatura()
returns void
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.assinatura_ativa(public.meu_restaurante()) then
    raise exception 'A assinatura do Mesari venceu. Renove em "Meu plano" para continuar lançando pedidos.';
  end if;
end;
$$;

-- Início do histórico de vendas que o plano permite ver.
create or replace function public.historico_inicio()
returns timestamptz
language sql
stable
security definer
set search_path = public
as $$
  select case when p.historico_dias is null then '-infinity'::timestamptz
              else date_trunc('day', now() at time zone 'America/Sao_Paulo') at time zone 'America/Sao_Paulo'
                   - make_interval(days => p.historico_dias) end
  from public.plano_do_restaurante(public.meu_restaurante()) p;
$$;

-- Tudo o que o app precisa para a tela "Meu plano".
create or replace function public.minha_assinatura()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_rid integer := public.meu_restaurante();
  v_a public.assinaturas;
  v_p public.planos;
begin
  if v_rid is null then raise exception 'Faça login para continuar'; end if;
  select * into v_a from public.assinaturas where restaurante_id = v_rid;
  v_p := public.plano_do_restaurante(v_rid);
  return jsonb_build_object(
    'restaurante_id', v_rid,
    'codigo', (select codigo from public.restaurante where id = v_rid),
    'plano', to_jsonb(v_p),
    'status', coalesce(v_a.status, 'expirada'),
    'ciclo', v_a.ciclo,
    'periodo_fim', v_a.periodo_fim,
    'renovacao_automatica', coalesce(v_a.renovacao_automatica, false),
    'ativa', public.assinatura_ativa(v_rid),
    'uso', jsonb_build_object(
      'mesas',   (select count(*) from public.mesas where restaurante_id = v_rid and ativa),
      'garcons', (select count(*) from public.profiles where restaurante_id = v_rid and ativo and papel = 'garcom'),
      'caixas',  (select count(*) from public.profiles where restaurante_id = v_rid and ativo and papel = 'caixa'),
      'areas',   (select count(*) from public.salao_areas where restaurante_id = v_rid)
    )
  );
end;
$$;

grant execute on function public.minha_assinatura() to authenticated;
revoke execute on function public.plano_do_restaurante(integer) from public, anon;
revoke execute on function public.assinatura_ativa(integer) from public, anon;

